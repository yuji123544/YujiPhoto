// Turn a .vfx.json manifest into Luau: an Effect table for the YujiFlipbook runtime
// (luau/YujiFlipbook.luau), plus a usage example.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadManifest } from "./build.mjs";
import { PALETTES } from "./preview.mjs";

export const RUNTIME = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "luau", "YujiFlipbook.luau");

const num = (v) => (Math.round(v * 1000) / 1000).toString();

/** Effect table as a Luau module returning it. palette picks default colours (ice, fire, …). */
export function effectModule(manifestFile, { palette = "ice" } = {}) {
  const m = loadManifest(manifestFile);
  const missing = m.layers.filter((l) => !l.assetId).map((l) => l.name);
  const pal = PALETTES[palette] || {};
  const colorOf = (l) => {
    const c = l.color || pal[l.name] || Object.entries(pal).find(([k]) => l.name.toLowerCase().includes(k))?.[1] || "#ffffff";
    return c.replace("#", "");
  };
  const layers = m.layers
    .map((l) => `\t\t{ name = "${l.name}", image = "rbxassetid://${l.assetId ?? 0}", color = Color3.fromHex("${colorOf(l)}"), lightEmission = ${num(l.lightEmission ?? 1)}, brightness = ${num(l.brightness ?? 1)} },`)
    .join("\n");
  const code = `-- ${m.name}: generated by yuji-vfx from ${path.basename(manifestFile)}. Layers bottom first, white textures tinted here.
return {
\tname = "${m.name}",
\tgrid = ${m.grid},
\tsize = ${m.size},
\tframes = ${m.frames},
\tfps = ${m.fps},
\tlayers = {
${layers}
\t},
}
`;
  return { code, missing, name: m.name };
}

export function usage(name) {
  return `-- LocalScript example (ReplicatedStorage has YujiFlipbook and VFX.${name})
local RS = game:GetService("ReplicatedStorage")
local YujiFlipbook = require(RS.YujiFlipbook)
local effect = require(RS.VFX.${name})

-- 1) Flat plate on the swing plane (UpVector = plane normal), recoloured with a palette:
local root = game.Players.LocalPlayer.Character:WaitForChild("HumanoidRootPart")
YujiFlipbook.plane(root.CFrame * CFrame.new(0, 0, -4) * CFrame.Angles(math.rad(90), 0, 0), Vector2.new(8, 8), effect, { palette = "fire" })

-- 2) Camera-facing particles (additive glow), e.g. a hit spark:
local att = Instance.new("Attachment", root)
local _, emit = YujiFlipbook.burst(att, effect, { palette = "void", scale = 5 })
emit()
`;
}

export function writeLuau(manifestFile, { palette, out } = {}) {
  const { code, missing, name } = effectModule(manifestFile, { palette });
  const dest = out || path.join(path.dirname(path.resolve(manifestFile)), `${name}.luau`);
  fs.writeFileSync(dest, code);
  return { file: dest, runtime: RUNTIME, missing, code, usage: usage(name) };
}
